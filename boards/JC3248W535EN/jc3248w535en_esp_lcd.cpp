void jc3248w535en_esp_lcd_init() {
    // Same AXS15231B_PANEL_BUS_QSPI_CONFIG values as OBD.  Assignment form
    // is required here because this translation unit is C++ and the current
    // ESP-IDF anonymous-union field order rejects the C designated initializer.
    spi_bus_config_t buscfg = {};
    buscfg.sclk_io_num = TFT_SCLK;
    buscfg.data0_io_num = TFT_D0;
    buscfg.data1_io_num = TFT_D1;
    buscfg.data2_io_num = TFT_D2;
    buscfg.data3_io_num = TFT_D3;
    buscfg.max_transfer_sz = kMaxTransferBytes;
    ESP_LOGI("JC3248", "Initialize SPI2 QSPI bus");
    ESP_ERROR_CHECK(spi_bus_initialize(SPI2_HOST, &buscfg, SPI_DMA_CH_AUTO));

    const esp_lcd_panel_io_spi_config_t io_config = AXS15231B_PANEL_IO_QSPI_CONFIG(TFT_CS, on_color_trans_done, nullptr);
    ESP_LOGI("JC3248", "Install esp_lcd_panel_io_spi");
    ESP_ERROR_CHECK(esp_lcd_new_panel_io_spi((esp_lcd_spi_bus_handle_t)SPI2_HOST, &io_config, &s_io));

    static const axs15231b_vendor_config_t vendor_config = {
        .init_cmds = lcd_init_cmds,
        .init_cmds_size = sizeof(lcd_init_cmds) / sizeof(lcd_init_cmds[0]),
        .flags = {.use_qspi_interface = 1},
    };
    const esp_lcd_panel_dev_config_t panel_config = {
        .reset_gpio_num = GPIO_NUM_NC,
        .rgb_ele_order = LCD_RGB_ELEMENT_ORDER_RGB,
        .bits_per_pixel = 16,
        .vendor_config = (void *)&vendor_config,
    };
    ESP_LOGI("JC3248", "Install literal OBD AXS15231B driver");
    ESP_ERROR_CHECK(esp_lcd_new_panel_axs15231b(s_io, &panel_config, &s_panel));

    s_trans_done_sem = xSemaphoreCreateCounting(1, 0);
    s_trans_buf_1 = static_cast<uint16_t *>(heap_caps_malloc(kTransportBytes, MALLOC_CAP_DMA));
    s_trans_buf_2 = static_cast<uint16_t *>(heap_caps_malloc(kTransportBytes, MALLOC_CAP_DMA));
    if (!s_trans_done_sem || !s_trans_buf_1 || !s_trans_buf_2) abort();

    ESP_ERROR_CHECK(esp_lcd_panel_reset(s_panel));
    ESP_ERROR_CHECK(esp_lcd_panel_init(s_panel));
    ESP_ERROR_CHECK(esp_lcd_panel_disp_on_off(s_panel, false));
    Serial.println("[JC3248] esp_lcd panel initialized");
}

[[noreturn]] void jc3248w535en_esp_lcd_test() {
    uint16_t *frame = static_cast<uint16_t *>(heap_caps_malloc(kPixels * sizeof(uint16_t), MALLOC_CAP_SPIRAM));
    if (!frame) abort();
    fill_quadrants(frame);
    Serial.println("[JC3248] static quadrant test 320x480");
    flush_frame(frame);
    Serial.println("[JC3248] quadrant pattern held; no further frame");
    Serial.flush();
    while (true) vTaskDelay(pdMS_TO_TICKS(1000));
}

void jc3248w535en_esp_lcd_present_physical(const uint16_t *physical_frame) {
    if (!physical_frame || !s_panel || !s_trans_done_sem || !s_trans_buf_1 || !s_trans_buf_2) return;

    // Geometry is already physical 320x480 here. Keep the validated DMA
    // chunking unchanged and only encode RGB565 into the panel byte order.
    constexpr uint32_t rows_per_transfer = kTransportPixels / kWidth;
    uint16_t *transport = s_trans_buf_1;
    for (uint32_t y = 0; y < kHeight; y += rows_per_transfer) {
        const uint32_t rows = ((kHeight - y) < rows_per_transfer) ? (kHeight - y) : rows_per_transfer;
        const uint32_t transfer_pixels = rows * kWidth;
        const uint32_t physical_offset = y * kWidth;
        for (uint32_t i = 0; i < transfer_pixels; ++i) {
            transport[i] = panel565(physical_frame[physical_offset + i]);
        }
        Serial.printf("[GFX FLUSH] physical y=%u rows=%u\\n", (unsigned)y, (unsigned)rows);
        ESP_ERROR_CHECK(esp_lcd_panel_draw_bitmap(s_panel, 0, y, kWidth, y + rows, transport));
        xSemaphoreTake(s_trans_done_sem, portMAX_DELAY);
        transport = (transport == s_trans_buf_1) ? s_trans_buf_2 : s_trans_buf_1;
    }
}
