esp_lcd_panel_io_handle_t s_io = nullptr;
esp_lcd_panel_handle_t s_panel = nullptr;
SemaphoreHandle_t s_trans_done_sem = nullptr;
uint16_t *s_trans_buf_1 = nullptr;
uint16_t *s_trans_buf_2 = nullptr;

static bool on_color_trans_done(esp_lcd_panel_io_handle_t, esp_lcd_panel_io_event_data_t *, void *) {
    BaseType_t task_awake = pdFALSE;
    if (s_trans_done_sem) xSemaphoreGiveFromISR(s_trans_done_sem, &task_awake);
    return task_awake == pdTRUE;
}

uint16_t panel565(uint16_t color) {
    return static_cast<uint16_t>((color >> 8) | (color << 8));
}

void fill_quadrants(uint16_t *frame) {
    const uint16_t colors[2][2] = {{panel565(kRed), panel565(kGreen)}, {panel565(kBlue), panel565(kWhite)}};
    for (uint32_t y = 0; y < kHeight; ++y) {
        for (uint32_t x = 0; x < kWidth; ++x) {
            const bool right = x >= kWidth / 2;
            const bool bottom = y >= kHeight / 2;
            frame[y * kWidth + x] = colors[bottom][right];
        }
    }
}

void flush_frame(uint16_t *frame) {
    constexpr uint32_t rows_per_transfer = kTransportPixels / kWidth;
    uint16_t *transport = s_trans_buf_1;
    for (uint32_t y = 0; y < kHeight; y += rows_per_transfer) {
        const uint32_t rows = ((kHeight - y) < rows_per_transfer) ? (kHeight - y) : rows_per_transfer;
        memcpy(transport, frame + y * kWidth, rows * kWidth * sizeof(uint16_t));
        Serial.printf("[CHUNK %u] esp_lcd draw y=%u rows=%u\\n", (unsigned)(y / rows_per_transfer), (unsigned)y, (unsigned)rows);
        ESP_ERROR_CHECK(esp_lcd_panel_draw_bitmap(s_panel, 0, y, kWidth, y + rows, transport));
        xSemaphoreTake(s_trans_done_sem, portMAX_DELAY);
        transport = (transport == s_trans_buf_1) ? s_trans_buf_2 : s_trans_buf_1;
    }
}
